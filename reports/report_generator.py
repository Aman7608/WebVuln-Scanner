"""
Report Generator - creates HTML and PDF reports for a finished scan.

HTML: uses a Jinja2 template (reports/templates/report.html). Jinja2 comes
      with Flask. Auto-escaping is ON, so payloads like <wvs...> in the
      evidence are shown as text and can never run inside the report.

PDF:  uses ReportLab's "platypus" module, which builds a PDF from a list of
      blocks (paragraphs, tables, spacers). ReportLab paragraphs understand a
      small set of HTML-like tags, so we escape all scan text first.
"""

import io
import os
from datetime import datetime
from xml.sax.saxutils import escape

from jinja2 import Environment, FileSystemLoader, select_autoescape
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import (KeepTogether, Paragraph, SimpleDocTemplate, Spacer, Table,
                                TableStyle)

TEMPLATE_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "templates")
_jinja = Environment(loader=FileSystemLoader(TEMPLATE_DIR),
                     autoescape=select_autoescape(["html"]))

SEVERITY_COLORS = {
    "Critical": colors.HexColor("#c9184a"),
    "High": colors.HexColor("#e85d04"),
    "Medium": colors.HexColor("#c98a00"),
    "Low": colors.HexColor("#0077b6"),
    "Informational": colors.HexColor("#6c757d"),
}


def generated_time():
    return datetime.now().strftime("%Y-%m-%d %H:%M:%S")


# ------------------------------------------------------------------ HTML
def generate_html_report(scan, findings, counts, urls):
    template = _jinja.get_template("report.html")
    return template.render(scan=scan, findings=findings, counts=counts, urls=urls,
                           generated_at=generated_time())


# ------------------------------------------------------------------ PDF
def safe(text):
    """Escape text for a ReportLab Paragraph and keep line breaks."""
    return escape(str(text or "")).replace("\n", "<br/>")


def generate_pdf_report(scan, findings, counts, urls):
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(buffer, pagesize=A4, leftMargin=18 * mm, rightMargin=18 * mm,
                            topMargin=18 * mm, bottomMargin=18 * mm,
                            title=f"WebVuln Scanner Report - Scan #{scan['id']}",
                            author="WebVuln Scanner")

    styles = getSampleStyleSheet()
    body = ParagraphStyle("body", parent=styles["BodyText"], fontSize=9.5, leading=13)
    small = ParagraphStyle("small", parent=body, fontSize=8, leading=10.5, textColor=colors.HexColor("#555555"))
    mono = ParagraphStyle("mono", parent=body, fontName="Courier", fontSize=7.5, leading=9.5,
                          backColor=colors.HexColor("#f4f6fa"), borderPadding=4)
    h1, h2, h3 = styles["Title"], styles["Heading2"], styles["Heading4"]

    story = [
        Paragraph("Web Application Vulnerability Report", h1),
        Paragraph(f"Generated by WebVuln Scanner on {generated_time()}", small),
        Spacer(1, 8),
        Paragraph("Target information", h2),
    ]

    status = scan["status"]
    if scan.get("error_message"):
        status += f" - {scan['error_message']}"
    info_rows = [
        ["Target URL", scan["target_url"]],
        ["Scan ID", f"#{scan['id']}"],
        ["Status", status],
        ["Started", scan["started_at"]],
        ["Finished", scan.get("finished_at") or "-"],
        ["Pages discovered", str(scan["pages_found"])],
        ["Requests sent", str(scan["requests_sent"])],
        ["Total vulnerabilities", str(len(findings))],
    ]
    info_table = Table([[Paragraph(safe(a), body), Paragraph(safe(b), body)] for a, b in info_rows],
                       colWidths=[45 * mm, 129 * mm])
    info_table.setStyle(TableStyle([
        ("LINEBELOW", (0, 0), (-1, -1), 0.4, colors.HexColor("#e3e7ef")),
        ("TEXTCOLOR", (0, 0), (0, -1), colors.HexColor("#475467")),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
    ]))
    story += [info_table, Spacer(1, 6), Paragraph("Severity distribution", h2)]

    levels = list(counts.keys())
    severity_table = Table([levels, [str(counts[level]) for level in levels]], colWidths=[34.8 * mm] * 5)
    severity_style = [
        ("ALIGN", (0, 0), (-1, -1), "CENTER"),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, 0), 8),
        ("FONTSIZE", (0, 1), (-1, 1), 14),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("TOPPADDING", (0, 1), (-1, 1), 6), ("BOTTOMPADDING", (0, 1), (-1, 1), 6),
        ("BOX", (0, 0), (-1, -1), 0.4, colors.HexColor("#e3e7ef")),
    ]
    for column, level in enumerate(levels):
        severity_style.append(("BACKGROUND", (column, 0), (column, 0), SEVERITY_COLORS[level]))
    severity_table.setStyle(TableStyle(severity_style))
    story += [
        severity_table, Spacer(1, 4),
        Paragraph("Severity = impact x exploitability x confidence (0-25). Critical &gt;= 20, "
                  "High &gt;= 12, Medium &gt;= 6, Low &gt;= 3, otherwise Informational.", small),
        Paragraph("Detailed findings", h2),
    ]

    if not findings:
        story.append(Paragraph("No vulnerabilities were found with the selected checks.", body))

    for number, f in enumerate(findings, start=1):
        color = SEVERITY_COLORS.get(f["severity"], colors.grey).hexval()[2:]
        rows = [["Affected URL", Paragraph(safe(f["url"]), body)]]
        if f.get("parameter"):
            rows.append(["Parameter", Paragraph(safe(f["parameter"]), body)])
        rows += [
            ["Severity", Paragraph(f'<font color="#{color}"><b>{safe(f["severity"])}</b></font> '
                                   f'(risk score {f["risk_score"]})', body)],
            ["Confidence", Paragraph(safe(f["confidence"]), body)],
            ["Description", Paragraph(safe(f["description"]), body)],
            ["Evidence", Paragraph(safe(f["evidence"]), mono)],
            ["Remediation", Paragraph(safe(f["remediation"]), body)],
        ]
        table = Table(rows, colWidths=[30 * mm, 144 * mm])
        table.setStyle(TableStyle([
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ("FONTSIZE", (0, 0), (0, -1), 8.5),
            ("TEXTCOLOR", (0, 0), (0, -1), colors.HexColor("#475467")),
            ("LINEBEFORE", (0, 0), (0, -1), 3, SEVERITY_COLORS.get(f["severity"], colors.grey)),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
        ]))
        heading = Paragraph(f'{number}. {safe(f["name"])}', h3)
        # Keep the heading together with the start of its table
        story += [KeepTogether([heading, table]), Spacer(1, 8)]

    story.append(Paragraph(f"Discovered URLs ({len(urls)})", h2))
    url_rows = [["Source", "URL", "Status"]] + [
        [u["source"], Paragraph(safe(u["url"]), small), str(u["status_code"] or "")] for u in urls]
    url_table = Table(url_rows, colWidths=[22 * mm, 136 * mm, 16 * mm], repeatRows=1)
    url_table.setStyle(TableStyle([
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, -1), 8),
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#f4f6fa")),
        ("LINEBELOW", (0, 0), (-1, -1), 0.3, colors.HexColor("#e3e7ef")),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
    ]))
    story += [url_table, Spacer(1, 12), Paragraph(
        "This report was produced by an automated scanner and may contain false positives or miss "
        "vulnerabilities. Confirm every finding manually. Only scan systems you are authorized to test.",
        small)]

    doc.build(story)
    return buffer.getvalue()
